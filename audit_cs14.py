import os
import math
import torch
import torch.nn as nn
from transformers import AutoModelForCausalLM, AutoTokenizer
from peft import PeftModel

MODEL_ID = "HuggingFaceTB/SmolLM2-135M"
ADAPTER_PATH = "./outputs_iter_CS14"

QA_SUITE = [
    {
        "q": "What physical condition is required to convert virtual vacuum fluctuations into real observable photon pairs in the Dynamical Casimir Effect?",
        "a": "Non-adiabatic acceleration of boundary conditions mixing positive and negative frequency modes."
    },
    {
        "q": "How is the two-mode squeezing parameter r mathematically related to mirror motion in the Dynamical Casimir Effect?",
        "a": "The squeezing parameter r is directly proportional to the mirror non-adiabatic trajectory acceleration a."
    },
    {
        "q": "If a conducting mirror moves through the quantum vacuum at a constant, uniform relativistic velocity, how many real entangled photon pairs are created?",
        "a": "Zero real entangled pairs are created because uniform velocity motion is strictly adiabatic and preserves time translation symmetry."
    },
    {
        "q": "Why do the photon pairs generated by the Dynamical Casimir Effect violate classical probability bounds?",
        "a": "Because two-mode squeezing produces inter-mode quantum cross-correlations below the classical shot-noise limit."
    },
    {
        "q": "How does the creation of entangled pairs at an event horizon explain the geometric scaling of black hole thermodynamic entropy?",
        "a": "Tracing out the interior entangled mode leaves the exterior mode in a thermal mixed state with entanglement entropy proportional to the horizon area."
    }
]

# Standard baselines from repo (eval_pipeline.py)
BASELINE_ALGEBRA = [
    {"q": "Solve for x: 2x + 5 = 15", "a": "Subtract 5 from both sides to get 2x = 10. Divide by 2 to get x = 5."},
    {"q": "Expand the expression (x + 3)(x - 2).", "a": "Using FOIL: x^2 - 2x + 3x - 6 = x^2 + x - 6."},
    {"q": "What is the slope of the line y = -4x + 7?", "a": "The slope is -4."}
]

def evaluate(model, tokenizer, items, name=""):
    model.eval()
    total_loss = 0.0
    total_tokens = 0
    correct_tokens = 0
    
    with torch.no_grad():
        for item in items:
            messages = [{"role": "user", "content": item["q"]}, {"role": "assistant", "content": item["a"]}]
            full_str = tokenizer.apply_chat_template(messages, tokenize=False)
            prompt_str = tokenizer.apply_chat_template([{"role": "user", "content": item["q"]}], tokenize=False, add_generation_prompt=True)
            
            full_enc = tokenizer(full_str, return_tensors="pt")["input_ids"]
            prompt_len = len(tokenizer(prompt_str, return_tensors="pt")["input_ids"][0])
            
            outputs = model(full_enc)
            logits = outputs.logits
            
            shift_logits = logits[:, prompt_len-1:-1, :].contiguous()
            shift_labels = full_enc[:, prompt_len:].contiguous()
            
            loss_fn = nn.CrossEntropyLoss(reduction="sum")
            loss = loss_fn(shift_logits.view(-1, shift_logits.size(-1)), shift_labels.view(-1))
            
            n_tok = shift_labels.numel()
            total_loss += loss.item()
            total_tokens += n_tok
            
            preds = torch.argmax(shift_logits, dim=-1)
            correct_tokens += (preds == shift_labels).sum().item()
            
    mean_loss = total_loss / max(total_tokens, 1)
    tok_acc = (correct_tokens / max(total_tokens, 1)) * 100.0
    ppl = math.exp(mean_loss)
    return {"loss": round(mean_loss, 4), "tok_acc": round(tok_acc, 2), "ppl": round(ppl, 4)}

def main():
    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
    tokenizer.pad_token = tokenizer.eos_token
    if not tokenizer.chat_template:
        tokenizer.chat_template = "{% for message in messages %}{{'<|im_start|>' + message['role'] + '\\n' + message['content'] + '<|im_end|>\\n'}}{% endfor %}"
        
    print("1. Loading Base Model...")
    base_model = AutoModelForCausalLM.from_pretrained(MODEL_ID)
    base_qa = evaluate(base_model, tokenizer, QA_SUITE, "Base QA")
    base_alg = evaluate(base_model, tokenizer, BASELINE_ALGEBRA, "Base Algebra")
    
    print("\n2. Loading Model with CS14 Trained LoRA Adapter...")
    lora_model = PeftModel.from_pretrained(base_model, ADAPTER_PATH)
    lora_qa = evaluate(lora_model, tokenizer, QA_SUITE, "CS14 LoRA QA")
    lora_alg = evaluate(lora_model, tokenizer, BASELINE_ALGEBRA, "CS14 LoRA Algebra")
    
    print("\n" + "=" * 75)
    print("PHYSICAL AUDIT VERIFICATION RESULTS")
    print("=" * 75)
    print(f"{'Evaluation Set':<25} | {'Metric':<12} | {'Base Model':<15} | {'After CS14 LoRA':<15}")
    print("-" * 75)
    print(f"{'Quantum QA (CS14)':<25} | {'Cross-Entropy':<12} | {base_qa['loss']:<15} | {lora_qa['loss']:<15}")
    print(f"{'Quantum QA (CS14)':<25} | {'Token Acc':<12} | {base_qa['tok_acc']}%{'':<10} | {lora_qa['tok_acc']}%{'':<10}")
    print(f"{'Quantum QA (CS14)':<25} | {'Perplexity':<12} | {base_qa['ppl']:<15} | {lora_qa['ppl']:<15}")
    print("-" * 75)
    print(f"{'Algebra Baseline (CS1)':<25} | {'Cross-Entropy':<12} | {base_alg['loss']:<15} | {lora_alg['loss']:<15}")
    print(f"{'Algebra Baseline (CS1)':<25} | {'Token Acc':<12} | {base_alg['tok_acc']}%{'':<10} | {lora_alg['tok_acc']}%{'':<10}")
    print(f"{'Algebra Baseline (CS1)':<25} | {'Perplexity':<12} | {base_alg['ppl']:<15} | {lora_alg['ppl']:<15}")
    print("=" * 75)

if __name__ == "__main__":
    main()
