class ChatDataset(Dataset):
    def __init__(self, data_list, tokenizer, is_raw_passage=False):
        self.examples = []
        if is_raw_passage:
            # Raw text training
            enc = tokenizer(QUANTUM_PASSAGE, max_length=512, truncation=True, return_tensors="pt")
            self.examples.append((enc["input_ids"].squeeze(0), enc["input_ids"].squeeze(0)))
        else:
            for item in data_list:
                messages = [
                    {"role": "user", "content": item["question"]},
                    {"role": "assistant", "content": item["answer"]}
                ]
                prompt_messages = [{"role": "user", "content": item["question"]}]
                full_text = tokenizer.apply_chat_template(messages, tokenize=False)
                prompt_text = tokenizer.apply_chat_template(prompt_messages, tokenize=False, add_generation_prompt=True)
                
                full_enc = tokenizer(full_text, return_tensors="pt")["input_ids"].squeeze(0)
                prompt_len = len(tokenizer(prompt_text, return_tensors="pt")["input_ids"].squeeze(0))
                
                labels = full_enc.clone()
                labels[:prompt_len] = -100  # mask prompt tokens
                self.examples.append((full_enc, labels))

    def __len__(self):
        return len(self.examples)

    def __getitem__(self, idx):
        return self.examples[idx]

def chat_collate(batch):
    max_len = max(len(x[0]) for x in batch)
    input_ids = torch.full((len(batch), max_len), fill_value=0, dtype=torch.long)
    labels = torch.full((len(batch), max_len), fill_value=-100, dtype=torch.long)
    for i, (inp, lab) in enumerate(batch):
        input_ids[i, :len(inp)] = inp
        labels[i, :len(lab)] = lab
    return input_ids, labels

def evaluate_chat_qa(model, tokenizer, eval_suite):
    model.eval()
    total_loss = 0.0
    total_tokens = 0
    correct_tokens = 0
    total_f1 = 0.0
    
    with torch.no_grad():
        for item in eval_suite:
            prompt_messages = [{"role": "user", "content": item["question"]}]
            prompt_str = tokenizer.apply_chat_template(prompt_messages, tokenize=False, add_generation_prompt=True)
            target_str = item["answer"]
            
            prompt_enc = tokenizer(prompt_str, return_tensors="pt")
            target_enc = tokenizer(target_str, return_tensors="pt")
            
            input_ids = torch.cat([prompt_enc["input_ids"], target_enc["input_ids"]], dim=1).to(DEVICE)
            prompt_len = prompt_enc["input_ids"].shape[1]
            
            outputs = model(input_ids)
            logits = outputs.logits
            
            shift_logits = logits[:, prompt_len-1:-1, :].contiguous()
            shift_labels = input_ids[:, prompt_len:].contiguous()
            
            loss_fn = nn.CrossEntropyLoss(reduction="sum")
            loss = loss_fn(shift_logits.view(-1, shift_logits.size(-1)), shift_labels.view(-1))
            
            n_tok = shift_labels.numel()
            total_loss += loss.item()
            total_tokens += n_tok
            
            preds = torch.argmax(shift_logits, dim=-1)
            correct_tokens += (preds == shift_labels).sum().item()
            
            gen_out = model.generate(
                prompt_enc["input_ids"].to(DEVICE),
                max_new_tokens=40,
                pad_token_id=tokenizer.eos_token_id,
                do_sample=False
            )
            gen_text = tokenizer.decode(gen_out[0][prompt_len:], skip_special_tokens=True).strip().lower()
            
            gen_words = set(gen_text.split())
            target_words = set(target_str.lower().split())
            if gen_words and target_words:
                common = gen_words.intersection(target_words)
                prec = len(common) / len(gen_words)
                rec = len(common) / len(target_words)
                f1 = (2 * prec * rec) / (prec + rec) if (prec + rec) > 0 else 0.0
            else:
                f1 = 0.0
            total_f1 += f1
            
    mean_loss = total_loss / max(total_tokens, 1)
    tok_acc = (correct_tokens / max(total_tokens, 1)) * 100.0
    ppl = math.exp(mean_loss) if mean_loss < 20 else float('inf')
    qa_acc = (total_f1 / len(eval_suite)) * 100.0
    return {
        "eval_loss": round(mean_loss, 4),
        "token_acc": round(tok_acc, 2),
        "ppl": round(ppl, 2),
        "qa_accuracy": round(qa_acc, 2)
    }

def train_chat_lora(model, dataset, steps=15, lr=2e-4):
    model.train()
    loader = DataLoader(dataset, batch_size=1, shuffle=True, collate_fn=chat_collate)
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr)
    loss_fn = nn.CrossEntropyLoss(ignore_index=-100)
    
    step_count = 0
    losses = []
    while step_count < steps:
        for input_ids, labels in loader:
            input_ids = input_ids.to(DEVICE)
            labels = labels.to(DEVICE)
            
            optimizer.zero_grad()
            outputs = model(input_ids)
            logits = outputs.logits
            
            shift_logits = logits[..., :-1, :].contiguous()
            shift_labels = labels[..., 1:].contiguous()
            
            loss = loss_fn(shift_logits.view(-1, shift_logits.size(-1)), shift_labels.view(-1))
            loss.backward()
            optimizer.step()
            
            losses.append(loss.item())
            step_count += 1
            if step_count >= steps:
                break
    return {
        "start_loss": round(losses[0], 4) if losses else 0.0,
        "final_loss": round(losses[-1], 4) if losses else 0.0,
        "steps": step_count
    }

