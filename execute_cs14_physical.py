# Simple In-Memory Dataset
class TextDataset(Dataset):
    def __init__(self, texts, tokenizer, max_len=256):
        self.examples = []
        for text in texts:
            enc = tokenizer(text, max_length=max_len, truncation=True, return_tensors="pt")
            self.examples.append(enc["input_ids"].squeeze(0))
            
    def __len__(self):
        return len(self.examples)
        
    def __getitem__(self, idx):
        return self.examples[idx]

def collate_fn(batch):
    max_len = max(len(x) for x in batch)
    padded = torch.full((len(batch), max_len), fill_value=0, dtype=torch.long)
    for i, x in enumerate(batch):
        padded[i, :len(x)] = x
    return padded

# 4. PHYSICAL EVALUATION FUNCTION
def evaluate_model(model, tokenizer, qa_suite):
    model.eval()
    total_loss = 0.0
    total_tokens = 0
    correct_tokens = 0
    total_f1 = 0.0
    
    with torch.no_grad():
        for item in qa_suite:
            prompt = f"Question: {item['question']}\nAnswer: "
            target = item['answer']
            
            prompt_enc = tokenizer(prompt, return_tensors="pt")
            target_enc = tokenizer(target, return_tensors="pt")
            
            input_ids = torch.cat([prompt_enc["input_ids"], target_enc["input_ids"]], dim=1).to(DEVICE)
            prompt_len = prompt_enc["input_ids"].shape[1]
            
            outputs = model(input_ids)
            logits = outputs.logits
            
            # Compute loss only on target tokens
            shift_logits = logits[:, prompt_len-1:-1, :].contiguous()
            shift_labels = input_ids[:, prompt_len:].contiguous()
            
            loss_fn = nn.CrossEntropyLoss(reduction="sum")
            loss = loss_fn(shift_logits.view(-1, shift_logits.size(-1)), shift_labels.view(-1))
            
            n_tokens = shift_labels.numel()
            total_loss += loss.item()
            total_tokens += n_tokens
            
            preds = torch.argmax(shift_logits, dim=-1)
            correct_tokens += (preds == shift_labels).sum().item()
            
            # Generate greedy completion to evaluate answer accuracy
            gen_out = model.generate(
                prompt_enc["input_ids"].to(DEVICE),
                max_new_tokens=30,
                pad_token_id=tokenizer.eos_token_id,
                do_sample=False
            )
            gen_text = tokenizer.decode(gen_out[0][prompt_len:], skip_special_tokens=True).strip().lower()
            
            # Compute token overlap F1 with target
            gen_words = set(gen_text.split())
            target_words = set(target.lower().split())
            if gen_words and target_words:
                common = gen_words.intersection(target_words)
                prec = len(common) / len(gen_words)
                rec = len(common) / len(target_words)
                f1 = (2 * prec * rec) / (prec + rec) if (prec + rec) > 0 else 0.0
            else:
                f1 = 0.0
            total_f1 += f1
            
    mean_loss = total_loss / max(total_tokens, 1)
    token_acc = (correct_tokens / max(total_tokens, 1)) * 100.0
    ppl = math.exp(mean_loss) if mean_loss < 20 else float('inf')
    mean_qa_score = (total_f1 / len(qa_suite)) * 100.0
    
    return {
        "eval_loss": round(mean_loss, 4),
        "token_acc": round(token_acc, 2),
        "ppl": round(ppl, 2),
        "qa_accuracy": round(mean_qa_score, 2)
    }

# 5. PHYSICAL LORA TRAINING FUNCTION
def train_lora(model, train_texts, tokenizer, steps=15, lr=2e-4):
    model.train()
    dataset = TextDataset(train_texts, tokenizer)
    loader = DataLoader(dataset, batch_size=1, shuffle=True, collate_fn=collate_fn)
    
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr)
    loss_fn = nn.CrossEntropyLoss()
    
    step_count = 0
    losses = []
    
    while step_count < steps:
        for batch in loader:
            batch = batch.to(DEVICE)
            if batch.shape[1] < 2:
                continue
            inputs = batch[:, :-1]
            labels = batch[:, 1:]
            
            optimizer.zero_grad()
            outputs = model(inputs)
            logits = outputs.logits
            loss = loss_fn(logits.view(-1, logits.size(-1)), labels.view(-1))
            loss.backward()
            optimizer.step()
            
            losses.append(loss.item())
            step_count += 1
            if step_count >= steps:
                break
                
    return {
        "start_loss": round(losses[0], 4) if losses else 0.0,
        "final_loss": round(losses[-1], 4) if losses else 0.0,
        "steps": step_count
    }

